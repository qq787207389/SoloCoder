export function getItemById(id: string): Item | undefined {
  return ITEM_TEMPLATES.find((item) => item.id === id);
}

export function getRandomItemIdByRarity(rarity?: ItemRarity): string {
  let pool = ITEM_TEMPLATES;
  if (rarity) {
    pool = ITEM_TEMPLATES.filter((item) => item.rarity === rarity);
  }
  if (pool.length === 0) pool = ITEM_TEMPLATES;
  const weights = pool.map((item) => RARITY_WEIGHTS[item.rarity]);
  const totalWeight = weights.reduce((a, b) => a + b, 0);
  let random = Math.random() * totalWeight;
  for (let i = 0; i < pool.length; i++) {
    random -= weights[i];
    if (random <= 0) return pool[i].id;
  }
  return pool[0].id;
}

export function createItemInstance(templateId: string): Item | null {
  const template = getItemById(templateId);
  if (!template) return null;
  return {
    ...template,
    id: `${template.id}_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`,
    position: null,
    rotation: 0,
  };
}

export function getItemsByType(type: ItemType): Item[] {
  return ITEM_TEMPLATES.filter((item) => item.type === type);
}

