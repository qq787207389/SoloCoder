function makeItem(
  base: Partial<Item> & {
    id: string;
    name: string;
    description: string;
    type: ItemType;
    shape: ItemShape;
    icon: string;
    rarity: ItemRarity;
    element?: ElementType;
    stats?: Item['stats'];
    adjacencyEffects?: Item['adjacencyEffects'];
    effects?: Item['effects'];
    price?: number;
  }
): Item {
  return {
    id: base.id,
    name: base.name,
    description: base.description,
    shape: base.shape,
    rotation: 0,
    rarity: base.rarity,
    type: base.type,
    element: base.element || 'none',
    stats: base.stats || {},
    effects: base.effects || [{ type: 'passive', description: base.description }],
    adjacencyEffects: base.adjacencyEffects,
    position: null,
    icon: base.icon,
    color: base.color || ITEM_TYPE_COLORS[base.type],
    price: base.price,
  };
}

