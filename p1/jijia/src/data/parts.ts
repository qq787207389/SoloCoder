const createAffix = (id: string, type: Affix['type'], value: number): Affix => {
  const affixData: Record<string, { name: string; description: string }> = {
    'lightweight': { name: '轻量化', description: `重量减少 ${Math.abs(value)}` },
    'overload': { name: '过载', description: `伤害增加 ${value}` },
    'cooling': { name: '散热优化', description: `能量消耗减少 ${Math.abs(value)}` },
    'reinforced': { name: '强化护甲', description: `护甲增加 ${value}` },
    'agile': { name: '敏捷', description: `机动性增加 ${value}` },
    'energy_eff': { name: '能量效率', description: `最大能量增加 ${value}` },
  };
  return {
    id,
    ...affixData[id],
    type,
    value,
  };
};

