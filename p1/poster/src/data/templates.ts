import type { Template, CanvasElement, TextElement, ShapeElement } from '@/types';

function createId(prefix: string): string {
  return `${prefix}_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`;
}

function createTextElement(overrides: Partial<TextElement>): TextElement {
  return {
    id: createId('text'),
    type: 'text',
    name: overrides.text?.substring(0, 20) || '文本',
    left: 100,
    top: 100,
    width: 200,
    height: 50,
    rotation: 0,
    scaleX: 1,
    scaleY: 1,
    opacity: 1,
    visible: true,
    locked: false,
    zIndex: 0,
    blendMode: 'normal',
    text: '文本内容',
    fontFamily: 'Arial',
    fontSize: 24,
    fontWeight: 'normal',
    fontStyle: 'normal',
    lineHeight: 1.2,
    letterSpacing: 0,
    textAlign: 'center',
    fill: '#333333',
    stroke: '',
    strokeWidth: 0,
    shadows: [],
    textDecoration: 'none',
    ...overrides,
  };
}

function createShapeElement(overrides: Partial<ShapeElement>): ShapeElement {
  return {
    id: createId('shape'),
    type: 'shape',
    name: '形状',
    left: 100,
    top: 100,
    width: 200,
    height: 200,
    rotation: 0,
    scaleX: 1,
    scaleY: 1,
    opacity: 1,
    visible: true,
    locked: false,
    zIndex: 0,
    blendMode: 'normal',
    shapeType: 'rect',
    fill: '#3b82f6',
    stroke: '',
    strokeWidth: 0,
    strokeLineCap: 'butt',
    ...overrides,
  };
}

