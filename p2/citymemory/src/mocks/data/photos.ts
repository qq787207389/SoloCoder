export const getPhotoById = (id: string): Photo | undefined => {
  return mockPhotos.find(photo => photo.id === id);
};

export const getCommentsByPhotoId = (photoId: string): Comment[] => {
  return mockComments.filter(comment => comment.photoId === photoId);
};

export const getPhotosByDecade = (decade: string): Photo[] => {
  if (decade === 'all') return mockPhotos;
  return mockPhotos.filter(photo => photo.decade === decade);
};

export const getPhotosSortedByYear = (): Photo[] => {
  return [...mockPhotos].sort((a, b) => a.year - b.year);
};
